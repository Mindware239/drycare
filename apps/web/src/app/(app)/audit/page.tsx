"use client";
import { useState } from "react";
import { useApi } from "@/lib/api";
import { dateTime } from "@/lib/format";
import { Badge, Card, Input, PageHeader, Spinner, Table, Td, cx } from "@/components/ui";

export default function AuditPage() {
  const [tab, setTab] = useState<"audit" | "messages">("audit");
  const [action, setAction] = useState("");
  const logs = useApi<any[]>(`/audit-logs?limit=200${action ? `&action=${encodeURIComponent(action)}` : ""}`);
  const notes = useApi<any[]>(tab === "messages" ? "/notifications" : null);
  return (
    <div>
      <PageHeader title="Audit & messages" subtitle="Audit records are append-only and cannot be edited or deleted." />
      <div className="mb-3 flex gap-1 border-b border-slate-200">
        {(["audit", "messages"] as const).map((t) => (
          <button key={t} onClick={() => setTab(t)} className={cx("-mb-px border-b-2 px-3 py-2 text-sm font-medium", tab === t ? "border-brand-600 text-brand-700" : "border-transparent text-slate-500")}>
            {t === "audit" ? "Audit log" : "Customer messages"}
          </button>
        ))}
      </div>
      {tab === "audit" ? (
        <Card padded={false} actions={null}>
          <div className="p-3">
            <Input value={action} onChange={(e) => setAction(e.target.value)} placeholder="Filter by action prefix, e.g. refund, order., price" className="max-w-sm" />
          </div>
          {!logs.data ? (
            <Spinner />
          ) : (
            <Table head={["When", "Who", "Action", "Resource", "IP", "Request ID"]}>
              {logs.data.map((l) => (
                <tr key={l.id}>
                  <Td>{dateTime(l.createdAt)}</Td>
                  <Td>{l.actorName ?? "—"}</Td>
                  <Td>
                    <Badge color={/refund|cancel|failed|suspend|exception/.test(l.action) ? "red" : /price|override|handover/.test(l.action) ? "amber" : "slate"}>{l.action}</Badge>
                  </Td>
                  <Td className="font-mono text-xs">
                    {l.resourceType}/{l.resourceId?.slice(0, 8)}
                  </Td>
                  <Td className="text-xs">{l.ip}</Td>
                  <Td className="font-mono text-xs text-slate-400">{l.requestId?.slice(0, 8)}</Td>
                </tr>
              ))}
            </Table>
          )}
        </Card>
      ) : (
        <Card padded={false}>
          <p className="border-b border-slate-100 px-4 py-2 text-xs text-slate-500">
            Messages are generated by the background worker (<code>pnpm --filter @drycare/api worker</code>). Until an SMS/WhatsApp provider is connected they are logged, not sent to phones.
          </p>
          {!notes.data ? (
            <Spinner />
          ) : (
            <Table head={["When", "Event", "Channel", "To", "Message", "Status"]}>
              {notes.data.map((n) => (
                <tr key={n.id}>
                  <Td>{dateTime(n.createdAt)}</Td>
                  <Td>{n.eventType}</Td>
                  <Td>{n.channel}</Td>
                  <Td>{n.recipient ?? "—"}</Td>
                  <Td className="max-w-md truncate whitespace-normal text-xs">{n.body}</Td>
                  <Td>
                    <Badge color={n.status === "sent" ? "green" : n.status === "failed" ? "red" : "slate"}>{n.status}</Badge>
                  </Td>
                </tr>
              ))}
            </Table>
          )}
        </Card>
      )}
    </div>
  );
}
